    func testPickerKeysNeverPassCommandThrough() {
        typealias K = ClipPickerKey
        XCTAssertEqual(K.action(keyCode: K.returnKey, command: false, queryEmpty: true, isRepeat: false), .paste)
        XCTAssertEqual(K.action(keyCode: K.enterKey, command: false, queryEmpty: false, isRepeat: false), .paste)
        XCTAssertEqual(K.action(keyCode: K.escape, command: false, queryEmpty: true, isRepeat: false), .close)
        XCTAssertEqual(K.action(keyCode: K.up, command: false, queryEmpty: true, isRepeat: false), .up)
        XCTAssertEqual(K.action(keyCode: K.down, command: false, queryEmpty: true, isRepeat: true), .down)
        XCTAssertEqual(K.action(keyCode: K.digitKeys[0], command: true, queryEmpty: true, isRepeat: false), .quickPick(1))
        XCTAssertEqual(K.action(keyCode: K.digitKeys[8], command: true, queryEmpty: true, isRepeat: false), .quickPick(9))
        XCTAssertEqual(K.action(keyCode: K.pKey, command: true, queryEmpty: false, isRepeat: false), .togglePin)
        // ⌫ deletes only with an empty search (otherwise it edits the text), never on key repeat.
        XCTAssertEqual(K.action(keyCode: K.delete, command: false, queryEmpty: true, isRepeat: false), .delete)
        XCTAssertNil(K.action(keyCode: K.delete, command: false, queryEmpty: false, isRepeat: false))
        XCTAssertEqual(K.action(keyCode: K.delete, command: false, queryEmpty: true, isRepeat: true), .swallow)
        XCTAssertEqual(K.action(keyCode: K.delete, command: true, queryEmpty: false, isRepeat: false), .delete)
        // The approval cards' ⌘↩ and anything else with ⌘ never leave the picker.
        XCTAssertEqual(K.action(keyCode: K.returnKey, command: true, queryEmpty: true, isRepeat: false), .swallow)
        XCTAssertEqual(K.action(keyCode: 31 /* O */, command: true, queryEmpty: true, isRepeat: false), .swallow)
        XCTAssertEqual(K.action(keyCode: 0 /* A */, command: true, queryEmpty: true, isRepeat: false), .edit("selectAll:"))
        XCTAssertEqual(K.action(keyCode: 9 /* V */, command: true, queryEmpty: true, isRepeat: false), .edit("paste:"))
        // Typing goes to the search field.
        XCTAssertNil(K.action(keyCode: 0, command: false, queryEmpty: true, isRepeat: false))
    }

