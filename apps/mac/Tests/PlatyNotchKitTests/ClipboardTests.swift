        XCTAssertEqual(h.search("naive").count, 1, "file names are searched")
        XCTAssertEqual(h.search("").count, 4)
        XCTAssertEqual(h.search("  ").count, 4)
        XCTAssertTrue(h.search("coffee").isEmpty)
    }

