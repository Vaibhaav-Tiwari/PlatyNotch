final class ClipboardTests: XCTestCase {
    private var dirs: [URL] = []

    override func tearDown() {
        for d in dirs { try? FileManager.default.removeItem(at: d) }
        dirs = []
        super.tearDown()
    }

    private func tempDir() -> URL {
        let d = FileManager.default.temporaryDirectory.appendingPathComponent("ClipboardTests-\(UUID().uuidString)")
        dirs.append(d)
        return d.appendingPathComponent("clipboard", isDirectory: true)
    }

    private let t0 = Date(timeIntervalSince1970: 1_800_000_000)

    private func text(_ s: String, at offset: TimeInterval = 0, pinned: Bool = false) -> ClipItem {
        ClipItem(kind: .text(s), sourceBundleID: "com.apple.TextEdit", copiedAt: t0.addingTimeInterval(offset), pinned: pinned)
    }

    private func mode(_ url: URL) -> Int? {
        (try? FileManager.default.attributesOfItem(atPath: url.path)[.posixPermissions]) as? Int
    }

    // MARK: - Filter (C21)

    func testConcealedSkipped() {
        for marker in [ClipFilter.concealedType, ClipFilter.transientType, ClipFilter.autoGeneratedType] {
            XCTAssertFalse(ClipFilter.shouldRecord(types: ["public.utf8-plain-text", marker],
                                                   sourceBundleID: "com.apple.TextEdit", excluded: []), marker)
        }
        XCTAssertTrue(ClipFilter.shouldRecord(types: ["public.utf8-plain-text"],
                                              sourceBundleID: "com.apple.TextEdit", excluded: []))
    }

    func testPasswordManagerFloorAlwaysSkipped() {
        // Even when the user's exclude_apps list is empty, CaptureFilter's floor applies.
        for app in CaptureFilter.alwaysExcluded {
            XCTAssertFalse(ClipFilter.shouldRecord(types: ["public.utf8-plain-text"], sourceBundleID: app, excluded: []), app)
        }
        XCTAssertTrue(CaptureFilter.alwaysExcluded.contains("com.1password.1password"))
        XCTAssertTrue(CaptureFilter.alwaysExcluded.contains("com.apple.keychainaccess"))
    }

    func testExcludedAppSkipped() {
        XCTAssertFalse(ClipFilter.shouldRecord(types: ["public.utf8-plain-text"],
                                               sourceBundleID: "com.example.secret", excluded: ["com.example.secret"]))
        XCTAssertTrue(ClipFilter.shouldRecord(types: ["public.utf8-plain-text"],
                                              sourceBundleID: "com.example.other", excluded: ["com.example.secret"]))
        // An unknown source app is not attributed, so it is not recorded (CaptureFilter's rule).
        XCTAssertFalse(ClipFilter.shouldRecord(types: ["public.utf8-plain-text"], sourceBundleID: nil, excluded: []))
    }

    func testNSPasteboardSourceNamingExcludedAppSkipped() {
        // Frontmost is a browser, but the item says 1Password wrote it.
        XCTAssertFalse(ClipFilter.shouldRecord(types: ["public.utf8-plain-text", ClipFilter.sourceType],
                                               sourceBundleID: "com.apple.Safari",
                                               markedSource: "com.1password.1password", excluded: []))
        XCTAssertFalse(ClipFilter.shouldRecord(types: ["public.utf8-plain-text"], sourceBundleID: "com.apple.Safari",
                                               markedSource: " com.example.secret\n", excluded: ["com.example.secret"]))
        XCTAssertTrue(ClipFilter.shouldRecord(types: ["public.utf8-plain-text"], sourceBundleID: "com.apple.Safari",
                                              markedSource: "com.apple.Notes", excluded: []))
        XCTAssertTrue(ClipFilter.allowsMarkedSource(nil, excluded: []))
    }

    func testFilterStepsInOrder() {
        // Each step alone (the watcher reads the next thing only when the previous passes).
        XCTAssertFalse(ClipFilter.allowsApp("com.apple.Passwords", excluded: []))
        XCTAssertTrue(ClipFilter.allowsApp("com.apple.Notes", excluded: []))
        XCTAssertFalse(ClipFilter.allowsTypes(["public.png", ClipFilter.concealedType]))
        XCTAssertFalse(ClipFilter.allowsTypes(["com.agilebits.onepassword"]), "legacy 1Password marker")
        XCTAssertTrue(ClipFilter.allowsTypes(["public.png"]))
        XCTAssertTrue(ClipFilter.allowsTypes([]))
    }

    func testSourceWindowSkipsAnExcludedAppActiveSinceTheLastChange() {
        // 1Password copies, then hands focus back to Safari before the poll sees the change.
        var w = ClipSourceWindow(current: "com.1password.1password")
        w.activated("com.apple.Safari")
        XCTAssertFalse(w.allows(current: "com.apple.Safari", excluded: []))
        // After a processed change only the app in front then is remembered.
        w.reset(current: "com.apple.Safari")
        XCTAssertEqual(w.apps, ["com.apple.Safari"])
        XCTAssertTrue(w.allows(current: "com.apple.Safari", excluded: []))
        // Unrelated apps switching still record.
        w.activated("com.apple.Notes")
        w.activated("com.apple.TextEdit")
        XCTAssertTrue(w.allows(current: "com.apple.TextEdit", excluded: []))
        // The user's exclude_apps counts too, and the current app always does.
        XCTAssertFalse(w.allows(current: "com.apple.TextEdit", excluded: ["com.apple.Notes"]))
        XCTAssertFalse(w.allows(current: "com.apple.keychainaccess", excluded: []))
        XCTAssertFalse(w.allows(current: nil, excluded: []), "unknown current app")
        // An activation without a bundle id is not an excluded app.
        w.activated(nil)
        XCTAssertTrue(w.allows(current: "com.apple.TextEdit", excluded: []))
        XCTAssertEqual(ClipSourceWindow(current: nil).apps, [])
    }

