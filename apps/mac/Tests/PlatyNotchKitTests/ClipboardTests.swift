    func testDamagedIndexMovedAsideNeverDeletes() throws {
        let dir = tempDir()
        let store = ClipboardStore(directory: dir, now: { self.t0 })
        let img = try XCTUnwrap(store.recordImage(png: Data([9, 9]), width: 1, height: 1, source: "x"))
        let imageURL = try XCTUnwrap(store.imageURL(for: img))
        let index = dir.appendingPathComponent(ClipboardStore.indexName)
        try Data("{ not json".utf8).write(to: index)

        // A year later, so every image would count as an expired orphan.
        let later = t0.addingTimeInterval(365 * 86400)
        let damaged = ClipboardStore(directory: dir, now: { later })
        XCTAssertTrue(damaged.items.isEmpty)
        let aside = try XCTUnwrap(damaged.quarantinedIndex)
        XCTAssertTrue(aside.lastPathComponent.hasPrefix(ClipboardStore.corruptPrefix))
        XCTAssertEqual(try String(contentsOf: aside, encoding: .utf8), "{ not json")
        XCTAssertEqual(mode(aside), 0o600)
        damaged.sweepOrphanImages()
        damaged.trim()
        XCTAssertTrue(FileManager.default.fileExists(atPath: imageURL.path), "never deleted on a damaged index")

        // The next start sees no index at all, but the kept file still blocks the sweep.
        let next = ClipboardStore(directory: dir, now: { later })
        next.sweepOrphanImages()
        ClipboardStore.expireOnDisk(directory: dir, limit: 1, maxAge: 1, now: later)
        XCTAssertTrue(FileManager.default.fileExists(atPath: imageURL.path), "next start does not wipe images")
        // New items still work and keep their own image deletion.
        let fresh = try XCTUnwrap(next.recordImage(png: Data([5]), width: 1, height: 1, source: "x"))
        let freshURL = try XCTUnwrap(next.imageURL(for: fresh))
        next.remove(fresh.id)
        XCTAssertFalse(FileManager.default.fileExists(atPath: freshURL.path))

        // Only the user's explicit "Delete kept files" removes them.
        next.deleteKeptFiles()
        XCTAssertFalse(FileManager.default.fileExists(atPath: imageURL.path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: aside.path))
        XCTAssertNil(next.quarantinedIndex)
        XCTAssertFalse(next.hasKeptFiles)
    }

