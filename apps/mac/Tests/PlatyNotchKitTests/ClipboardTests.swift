    func testHashIsStableSHA256Prefix() {
        let a = ClipHash.of(.text("hello"))
        XCTAssertEqual(a, ClipHash.of(.text("hello")))
        XCTAssertNotEqual(a, ClipHash.of(.text("hello ")))
        XCTAssertNotEqual(ClipHash.of(.text("https://a.example")), ClipHash.of(.url(URL(string: "https://a.example")!)))
        // SHA-256("t:hello") starts 0x… : a fixed value, never Swift's per-launch hashValue.
        XCTAssertEqual(ClipHash.of(.text("hello")), ClipHash.of(.text("hello")))
        XCTAssertEqual(ClipHash.digest(Data()), Int(bitPattern: 0xe3b0c44298fc1c14), "SHA-256 of empty data, first 8 bytes")
        XCTAssertEqual(text("x").hash, ClipHash.of(.text("x")))
    }

    func testDuplicateMovesToTop() {
        var h = ClipboardHistory()
        h.record(text("a", at: 0), now: t0)
        let firstB = text("b", at: 1)
        h.record(firstB, now: t0)
        h.setPinned(firstB.id, true)
        h.record(text("c", at: 2), now: t0)
        let removed = h.record(text("b", at: 3), now: t0.addingTimeInterval(3))
        XCTAssertEqual(h.items.map(\.title), ["b", "c", "a"])
        XCTAssertEqual(h.items[0].id, firstB.id, "keeps its id")
        XCTAssertTrue(h.items[0].pinned, "keeps its pin")
        XCTAssertEqual(h.items[0].copiedAt, t0.addingTimeInterval(3))
        XCTAssertTrue(removed.isEmpty)
    }

