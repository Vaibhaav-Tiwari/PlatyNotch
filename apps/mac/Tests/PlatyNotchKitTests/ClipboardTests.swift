    func testLimitKeepsPinned() {
        var h = ClipboardHistory(limit: 3)
        let pinned = text("p", at: 0, pinned: true)
        h.record(pinned, now: t0)
        var removed: [ClipItem] = []
        for i in 1...5 { removed += h.record(text("\(i)", at: TimeInterval(i)), now: t0) }
        XCTAssertEqual(h.items.count, 3)
        XCTAssertEqual(h.items.map(\.title), ["5", "4", "p"])
        XCTAssertEqual(Set(removed.map(\.title)), ["1", "2", "3"])
        // All pinned and over the limit: nothing pinned goes.
        var all = ClipboardHistory(limit: 1)
        all.record(text("x", pinned: true), now: t0)
        all.record(text("y", pinned: true), now: t0)
        XCTAssertEqual(all.items.count, 2)
    }

    func testAgeTrim() {
        var h = ClipboardHistory(maxAge: 100)
        h.record(text("old", at: 0), now: t0)
        h.record(text("old pinned", at: 0, pinned: true), now: t0)
        h.record(text("new", at: 50), now: t0.addingTimeInterval(50))
        let removed = h.trim(now: t0.addingTimeInterval(120))
        XCTAssertEqual(removed.map(\.title), ["old"])
        XCTAssertEqual(h.items.map(\.title), ["new", "old pinned"])
        // Recording also trims by age.
        let gone = h.record(text("newest", at: 200), now: t0.addingTimeInterval(200))
        XCTAssertEqual(gone.map(\.title), ["new"])
    }

    func testSearchDiacritics() {
        var h = ClipboardHistory()
