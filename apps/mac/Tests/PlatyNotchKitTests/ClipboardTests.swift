        h.record(ClipItem(kind: .url(URL(string: "https://example.com/Résumé")!), copiedAt: t0), now: t0)
        h.record(ClipItem(kind: .files([URL(fileURLWithPath: "/Users/me/Naïve Plan.pdf")]), copiedAt: t0), now: t0)
