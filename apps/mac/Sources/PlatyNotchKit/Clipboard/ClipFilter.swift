import Foundation

/// Whether a pasteboard change may enter clipboard history (C21). Three steps, in order;
/// the watcher reads the next thing from the pasteboard only when the previous step
/// passed, so an excluded app's content is never read at all:
///
/// 1. The source app: `CaptureFilter.alwaysExcluded` (PlatyNotch, the login window and the
///    password managers: a floor the config cannot lower) plus the user's
///    `memory.exclude_apps`. The source is the frontmost app when the change is seen,
///    which is best effort: NSPasteboard does not say who wrote an item, and an app can
///    write the pasteboard from the background. An unknown source is not recorded.
/// 2. The item's types: anything marked concealed, transient or auto-generated
///    (nspasteboard.org) is skipped, as are two legacy markers with the same meaning.
/// 3. The item's own `org.nspasteboard.source`, when it names an excluded app (a password
///    manager's browser helper writing while the browser is frontmost).
///
/// The bundle lists are CaptureFilter's; nothing is duplicated here.
public enum ClipFilter {
    public static let concealedType = "org.nspasteboard.ConcealedType"
    public static let transientType = "org.nspasteboard.TransientType"
    public static let autoGeneratedType = "org.nspasteboard.AutoGeneratedType"
    /// The bundle id of the app that wrote the item (a string), when the app says so.
    public static let sourceType = "org.nspasteboard.source"
    /// Markers that predate nspasteboard.org: 1Password 7's own type and the original
    /// transient marker.
    public static let legacySecretTypes: Set<String> = ["com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]
    /// Every type that keeps an item out of history.
    public static let skippedTypes: Set<String> = legacySecretTypes.union([concealedType, transientType, autoGeneratedType])

    /// Step 1. `excluded` is the user's `memory.exclude_apps`; the floor is always added.
    public static func allowsApp(_ bundleID: String?, excluded: Set<String>) -> Bool {
        !CaptureFilter(excluded: excluded).isExcluded(bundleID)
    }

    /// Step 2.
    public static func allowsTypes(_ types: [String]) -> Bool {
        !types.contains(where: skippedTypes.contains)
    }

    /// Step 3. No marker (nil or blank) passes.
    public static func allowsMarkedSource(_ marked: String?, excluded: Set<String>) -> Bool {
        guard let id = marked?.trimmingCharacters(in: .whitespacesAndNewlines), !id.isEmpty else { return true }
        return !CaptureFilter(excluded: excluded).isExcluded(id)
    }

    /// All three steps.
    public static func shouldRecord(types: [String], sourceBundleID: String?, markedSource: String? = nil,
                                    excluded: Set<String>) -> Bool {
        allowsApp(sourceBundleID, excluded: excluded)
            && allowsTypes(types)
            && allowsMarkedSource(markedSource, excluded: excluded)
    }
}

/// The apps that may have made a pasteboard change (fix rounds 1 and 2). The change count
/// is only polled every 0.5 s, so the app in front at the poll may not be the one that
/// copied: a password manager that hands focus back right after copying would otherwise
/// have its copy attributed to the next app. Fed by app-activation notifications (no
/// polling).
///
/// Each app keeps the time it was last frontmost: when another app replaced it, or the
/// time it was seen in front. A change is skipped when the current app, or any app that
/// was frontmost within `horizon` before the change was seen, is excluded. Older entries
/// are pruned, so a password manager opened hours earlier never blocks an unrelated copy;
/// timing by when an app was *left* (not when it came forward) means a manager used for a
/// minute before copying is still caught.
public struct ClipSourceWindow: Equatable, Sendable {
    /// The app in front now (as far as the notifications said).
    public private(set) var current: String?
    /// Bundle id → when it was last frontmost (the current app: when it came forward).
    public private(set) var lastFrontmost: [String: Date]

    public init(current: String?, at: Date) {
        self.current = current.flatMap { $0.isEmpty ? nil : $0 }
        lastFrontmost = self.current.map { [$0: at] } ?? [:]
    }

    /// The apps in the window.
    public var apps: Set<String> { Set(lastFrontmost.keys) }

    /// An app became frontmost at `at`: the one it replaced was frontmost until then.
    public mutating func activated(_ bundleID: String?, at: Date) {
        if let current { lastFrontmost[current] = at }
        current = bundleID.flatMap { $0.isEmpty ? nil : $0 }
        if let current { lastFrontmost[current] = at }
    }

    /// After each processed change: only the app in front now.
    public mutating func reset(current: String?, at: Date) {
        self = ClipSourceWindow(current: current, at: at)
    }

    /// Drops apps last frontmost before `now - horizon` (never the current one).
    public mutating func prune(now: Date, horizon: TimeInterval) {
        let cutoff = now.addingTimeInterval(-horizon)
        lastFrontmost = lastFrontmost.filter { $0.key == current || $0.value >= cutoff }
    }

    /// Step 1 of `ClipFilter` over the current app and every app frontmost within
    /// `horizon` before `now` (the current one counts whatever its time).
    public func allows(current now: String?, excluded: Set<String>, at time: Date, horizon: TimeInterval) -> Bool {
        guard ClipFilter.allowsApp(now, excluded: excluded) else { return false }
        let cutoff = time.addingTimeInterval(-horizon)
        return lastFrontmost.allSatisfy { id, last in
            (id != current && last < cutoff) || ClipFilter.allowsApp(id, excluded: excluded)
        }
    }
}
